CREATE TABLE agente (
	id_agente INTEGER GENERATED BY DEFAULT AS IDENTITY,
	codigo_agente INTEGER,
	nombre VARCHAR2(50 CHAR) NOT NULL,
	apellido VARCHAR2(50 CHAR),
	direccion VARCHAR2(255 CHAR),
	antiguedad_empresa INTEGER,
	PRIMARY KEY (id_agente),
	UNIQUE (codigo_agente)
);

CREATE TABLE banco (
	id_banco INTEGER GENERATED BY DEFAULT AS IDENTITY,
	nombre VARCHAR2(100 CHAR) NOT NULL,
	nit VARCHAR2(20 CHAR),
	telefono VARCHAR2(25 CHAR),
	direccion VARCHAR2(255 CHAR),
	tasa_interes_base NUMERIC(7, 4),
	PRIMARY KEY (id_banco),
	UNIQUE (nit)
);

CREATE TABLE comprador (
	id_comprador INTEGER GENERATED BY DEFAULT AS IDENTITY,
	nombre VARCHAR2(50 CHAR) NOT NULL,
	apellido VARCHAR2(50 CHAR) NOT NULL,
	direccion VARCHAR2(150 CHAR),
	telefono VARCHAR2(25 CHAR),
	estado_civil VARCHAR2(30 CHAR),
	nacionalidad VARCHAR2(50 CHAR),
	edad INTEGER,
	PRIMARY KEY (id_comprador)
);

CREATE TABLE tipo_inmueble (
	id_tipo_inmueble INTEGER GENERATED BY DEFAULT AS IDENTITY,
	nombre_tipo VARCHAR2(255 CHAR) NOT NULL,
	PRIMARY KEY (id_tipo_inmueble)
);

CREATE TABLE vendedor (
	id_vendedor INTEGER GENERATED BY DEFAULT AS IDENTITY,
	nombre VARCHAR2(50 CHAR) NOT NULL,
	apellido VARCHAR2(50 CHAR),
	direccion VARCHAR2(150 CHAR),
	telefono VARCHAR2(25 CHAR),
	PRIMARY KEY (id_vendedor)
);

CREATE TABLE inmueble (
	id_inmueble INTEGER GENERATED BY DEFAULT AS IDENTITY,
	direccion VARCHAR2(200 CHAR) NOT NULL,
	precio NUMERIC(15, 2) NOT NULL,
	antiguedad INTEGER,
	modelo VARCHAR2(100 CHAR),
	material VARCHAR2(100 CHAR),
	metraje NUMERIC(12, 2),
	estado VARCHAR2(30 CHAR),
	disponibilidad VARCHAR2(30 CHAR),
	vendedor_id INTEGER,
	tipo_inmueble_id INTEGER,
	agente_id INTEGER,
	nombre VARCHAR2(100 CHAR) NOT NULL,
	ciudad VARCHAR2(100 CHAR) NOT NULL,
	descripcion VARCHAR2(2000 CHAR),
	imagen VARCHAR2(100 CHAR),
	destacado INTEGER NOT NULL,
	PRIMARY KEY (id_inmueble),
	FOREIGN KEY(vendedor_id) REFERENCES vendedor (id_vendedor),
	FOREIGN KEY(tipo_inmueble_id) REFERENCES tipo_inmueble (id_tipo_inmueble),
	FOREIGN KEY(agente_id) REFERENCES agente (id_agente)
);

CREATE INDEX ix_inmueble_agente_id ON inmueble (agente_id);

CREATE INDEX ix_inmueble_tipo_inmueble_id ON inmueble (tipo_inmueble_id);

CREATE INDEX ix_inmueble_vendedor_id ON inmueble (vendedor_id);

CREATE TABLE caracteristicas_inmueble (
	id_caracteristica INTEGER GENERATED BY DEFAULT AS IDENTITY,
	num_habitaciones INTEGER,
	num_banos INTEGER,
	num_parqueaderos INTEGER,
	estrato INTEGER,
	piso INTEGER,
	estado_conservacion VARCHAR2(30 CHAR),
	inmueble_id INTEGER NOT NULL,
	PRIMARY KEY (id_caracteristica),
	UNIQUE (inmueble_id),
	FOREIGN KEY(inmueble_id) REFERENCES inmueble (id_inmueble)
);

CREATE TABLE oferta (
	id_oferta INTEGER GENERATED BY DEFAULT AS IDENTITY,
	monto NUMERIC(15, 2),
	forma_pago VARCHAR2(50 CHAR),
	tiempo_pago VARCHAR2(100 CHAR),
	fecha DATE,
	hora DATE,
	estado VARCHAR2(30 CHAR),
	comprador_id INTEGER,
	inmueble_id INTEGER,
	PRIMARY KEY (id_oferta),
	FOREIGN KEY(comprador_id) REFERENCES comprador (id_comprador),
	FOREIGN KEY(inmueble_id) REFERENCES inmueble (id_inmueble)
);

CREATE INDEX ix_oferta_comprador_id ON oferta (comprador_id);

CREATE INDEX ix_oferta_inmueble_id ON oferta (inmueble_id);

CREATE TABLE prestamo (
	id_prestamo INTEGER GENERATED BY DEFAULT AS IDENTITY,
	monto_prestado NUMERIC(15, 2) NOT NULL,
	tasa_interes NUMERIC(7, 4) NOT NULL,
	plazo_meses INTEGER NOT NULL,
	fecha_desembolso DATE,
	estado VARCHAR2(30 CHAR) NOT NULL,
	banco_id INTEGER NOT NULL,
	comprador_id INTEGER NOT NULL,
	inmueble_id INTEGER NOT NULL,
	PRIMARY KEY (id_prestamo),
	FOREIGN KEY(banco_id) REFERENCES banco (id_banco),
	FOREIGN KEY(comprador_id) REFERENCES comprador (id_comprador),
	FOREIGN KEY(inmueble_id) REFERENCES inmueble (id_inmueble)
);

CREATE INDEX ix_prestamo_banco_id ON prestamo (banco_id);

CREATE INDEX ix_prestamo_comprador_id ON prestamo (comprador_id);

CREATE INDEX ix_prestamo_inmueble_id ON prestamo (inmueble_id);

CREATE TABLE solicitud (
	id_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY,
	comprador_id INTEGER NOT NULL,
	inmueble_id INTEGER,
	correo VARCHAR2(100 CHAR) NOT NULL,
	mensaje VARCHAR2(1000 CHAR),
	fecha DATE NOT NULL,
	estado VARCHAR2(30 CHAR) NOT NULL,
	PRIMARY KEY (id_solicitud),
	FOREIGN KEY(comprador_id) REFERENCES comprador (id_comprador),
	FOREIGN KEY(inmueble_id) REFERENCES inmueble (id_inmueble)
);

CREATE INDEX ix_solicitud_comprador_id ON solicitud (comprador_id);

CREATE INDEX ix_solicitud_inmueble_id ON solicitud (inmueble_id);

CREATE TABLE acuerdo (
	id_acuerdo INTEGER GENERATED BY DEFAULT AS IDENTITY,
	fecha DATE,
	monto_acordado NUMERIC(15, 2),
	condiciones VARCHAR2(500 CHAR),
	estado VARCHAR2(30 CHAR),
	oferta_id INTEGER,
	PRIMARY KEY (id_acuerdo),
	FOREIGN KEY(oferta_id) REFERENCES oferta (id_oferta)
);

CREATE INDEX ix_acuerdo_oferta_id ON acuerdo (oferta_id);

CREATE TABLE contra_oferta (
	id_contra_oferta INTEGER GENERATED BY DEFAULT AS IDENTITY,
	monto NUMERIC(15, 2),
	fecha DATE,
	hora DATE,
	estado VARCHAR2(30 CHAR),
	oferta_id INTEGER,
	PRIMARY KEY (id_contra_oferta),
	FOREIGN KEY(oferta_id) REFERENCES oferta (id_oferta)
);

CREATE INDEX ix_contra_oferta_oferta_id ON contra_oferta (oferta_id);

CREATE TABLE compra (
	id_compra INTEGER GENERATED BY DEFAULT AS IDENTITY,
	fecha_compra DATE,
	monto_final NUMERIC(15, 2),
	forma_pago VARCHAR2(50 CHAR),
	acuerdo_id INTEGER,
	PRIMARY KEY (id_compra),
	FOREIGN KEY(acuerdo_id) REFERENCES acuerdo (id_acuerdo)
);

CREATE INDEX ix_compra_acuerdo_id ON compra (acuerdo_id);
